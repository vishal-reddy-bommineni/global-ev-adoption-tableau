"""Recompute every headline number and hypothesis test shown in the dashboards.

Usage:  python src/analysis.py

Reads data/processed/EV_master_analytical.xlsx (the Tableau data source) and writes
results/RESULTS.md and results/figures/*.png. Every number quoted in the README comes from this script.

Note on the data: the IEA rounds every value to two significant figures, so country values do not
add up exactly to regional or world totals (country shares of world sales sum to 93-103% per year).
"""
from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "processed" / "EV_master_analytical.xlsx"
RES = ROOT / "results"
FIG = RES / "figures"
POP_COL = "Population"
BLUE, ORANGE, GREY, RED = "#2b6cb0", "#dd6b20", "#a0aec0", "#c53030"

lines: list[str] = []


def out(s: str = ""):
    print(s)
    lines.append(s)


def table(df: pd.DataFrame, floatfmt: str = "{:,.1f}"):
    cols = list(df.columns)
    out("| " + " | ".join(map(str, cols)) + " |")
    out("|" + "---|" * len(cols))
    for _, r in df.iterrows():
        cells = [floatfmt.format(v) if isinstance(v, (float, np.floating)) and not pd.isna(v) else
                 ("" if pd.isna(v) else f"{v:,}" if isinstance(v, (int, np.integer)) else str(v)) for v in r]
        out("| " + " | ".join(cells) + " |")
    out()


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def spearman(x, y):
    r = stats.spearmanr(x, y)
    return float(r.statistic), float(r.pvalue)


def main():
    FIG.mkdir(parents=True, exist_ok=True)
    sheets = pd.read_excel(DATA, sheet_name=None)
    m, tech, proj = sheets["Master_Analytical"], sheets["Master_Cars_Tech"], sheets["Master_Projection"]
    hist = m[m.Category == "Historical"]
    world = hist[hist.Region_Country == "World"].set_index("Year").sort_index()
    ctry = hist[hist.Entity_Type == "country"]          # 55 countries + the 5 large IEA markets

    out("# Results (generated by `python src/analysis.py`)")
    out()
    # ------------------------------------------------------------------ 1. global picture
    out("## 1. Global EV market, 2010-2025 (cars)")
    y0, y1 = world.loc[2010], world.loc[2025]
    yoy = world.EV_Sales_Cars_Total.pct_change() * 100
    out(f"- EV car sales: {y0.EV_Sales_Cars_Total:,.0f} (2010) -> {y1.EV_Sales_Cars_Total:,.0f} (2025), "
        f"{y1.EV_Sales_Cars_Total / y0.EV_Sales_Cars_Total:,.0f}x")
    out(f"- EV car stock: {y0.EV_Stock_Cars_Total:,.0f} -> {y1.EV_Stock_Cars_Total:,.0f}; "
        f"2015 -> 2025: {world.loc[2015].EV_Stock_Cars_Total:,.0f} -> {y1.EV_Stock_Cars_Total:,.0f} "
        f"({y1.EV_Stock_Cars_Total / world.loc[2015].EV_Stock_Cars_Total:.0f}x)")
    out(f"- EV share of new car sales: {y0.EV_Sales_Share_Cars}% -> {y1.EV_Sales_Share_Cars:.0f}% "
        f"(about 1 in {100 / y1.EV_Sales_Share_Cars:.0f} new cars)")
    out(f"- Public charging points: {y0.Charging_Total:,.0f} -> {y1.Charging_Total:,.0f}")
    out(f"- Year-over-year sales growth: 2019 {yoy[2019]:+.0f}% (slowdown), 2021 {yoy[2021]:+.0f}% (rebound), "
        f"2025 {yoy[2025]:+.0f}%")
    out()
    g = world[["EV_Sales_Cars_Total", "EV_Stock_Cars_Total", "EV_Sales_Share_Cars", "Charging_Total"]].copy()
    g.columns = ["sales", "stock", "sales share %", "chargers"]
    g.insert(1, "sales YoY %", yoy.round(0))
    table(g.reset_index().rename(columns={"Year": "year"}).astype({"year": int}), "{:,.1f}")

    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(world.index, world.EV_Stock_Cars_Total / 1e6, "o-", color=ORANGE, label="EV car stock")
    ax.plot(world.index, world.EV_Sales_Cars_Total / 1e6, "o-", color=BLUE, label="EV car sales")
    ax.set_ylabel("millions of cars")
    ax.set_title("World EV cars, 2010-2025 (IEA)", fontsize=10)
    ax.legend(frameon=False)
    style(ax)
    fig.tight_layout()
    fig.savefig(FIG / "global_trend.png", dpi=160)
    plt.close(fig)

    # ------------------------------------------------------------------ 2. leaders
    out("## 2. Who leads?")
    small = ctry[ctry.Geo_type == "country"]
    cum_small = small.groupby("Region_Country").EV_Sales_Cars_Total.sum().nlargest(5)
    cum_all = ctry.groupby("Region_Country").EV_Sales_Cars_Total.sum().nlargest(5)
    out("Cumulative EV car sales 2010-2025, individual countries (the dashboard's 'Countries only' view): "
        + ", ".join(f"{k} {v / 1e6:.2f}M" for k, v in cum_small.items()))
    out()
    out("Including the large markets IEA reports as aggregates: "
        + ", ".join(f"{k} {v / 1e6:.1f}M" for k, v in cum_all.items()))
    out()
    top10_small = small.groupby("Region_Country").EV_Sales_Cars_Total.sum().nlargest(10)
    eu = small[small.Region == "Europe"].Region_Country.unique()
    out(f"European countries in the 'countries only' top 10: {sum(c in eu for c in top10_small.index)} of 10")
    out()
    sh25 = ctry[ctry.Year == 2025].set_index("Region_Country").EV_Sales_Share_Cars.nlargest(8)
    out("EV share of new car sales, 2025: " + ", ".join(f"{k} {v:.0f}%" for k, v in sh25.items()))
    out()
    big3 = {r: hist[(hist.Region_Country == r)].set_index("Year").EV_Sales_Cars_Total.reindex([2025]).iloc[0]
            for r in ["China", "Europe", "United States"]}
    out("Share of world EV car sales in 2025: " + ", ".join(
        f"{k} {v / y1.EV_Sales_Cars_Total:.1%}" for k, v in big3.items())
        + f"; together {sum(big3.values()) / y1.EV_Sales_Cars_Total:.1%}")
    out()

    # emerging markets: CAGR of EV car sales 2014-2024 (the executive overview's 'Top 10 emerging markets')
    s = ctry.pivot_table(index="Region_Country", columns="Year", values="EV_Sales_Cars_Total")
    cagr = (((s[2024] / s[2014]) ** (1 / 10) - 1) * 100).dropna().sort_values(ascending=False)
    em = pd.DataFrame({"country": cagr.index[:10], "CAGR 2014-2024 %": cagr.values[:10].round(1),
                       "sales 2014": s.loc[cagr.index[:10], 2014].values.astype(int),
                       "sales 2024": s.loc[cagr.index[:10], 2024].values.astype(int),
                       "2025 EV share %": [ctry[(ctry.Region_Country == c) & (ctry.Year == 2025)].EV_Sales_Share_Cars.max()
                                           for c in cagr.index[:10]]})
    out("Fastest-growing markets (compound annual growth of EV car sales, 2014-2024):")
    out()
    table(em, "{:,.1f}")

    # ------------------------------------------------------------------ 3. H2 technology
    out("## 3. H2: battery-electric cars are taking over")
    wt = tech[(tech.Region_Country == "World") & (tech.Category == "Historical")]
    sales_pt = wt.pivot_table(index="Year", columns="Powertrain", values="EV_Sales_Cars")
    stock_pt = wt.pivot_table(index="Year", columns="Powertrain", values="EV_Stock_Cars")
    shr = sales_pt.div(sales_pt.sum(axis=1), axis=0) * 100
    shr_stock = stock_pt.div(stock_pt.sum(axis=1), axis=0) * 100
    out(f"- BEV share of EV car sales: {shr.BEV[2012]:.0f}% (2012, PHEV {shr.PHEV[2012]:.0f}%) -> "
        f"{shr.BEV[2019]:.0f}% (2019 peak) -> {shr.BEV[2024]:.1f}% (2024) -> {shr.BEV[2025]:.1f}% (2025)")
    tp = tech[(tech.Category == "Historical") & (tech.Powertrain == "PHEV")].pivot_table(
        index="Region_Country", columns="Year", values="EV_Sales_Cars")
    out(f"- PHEV share recovered from {shr.PHEV[2019]:.0f}% (2019) to {shr.PHEV[2024]:.0f}% (2024); China accounts for "
        f"{(tp.loc['China', 2024] - tp.loc['China', 2019]) / (tp.loc['World', 2024] - tp.loc['World', 2019]):.0%} "
        "of the extra PHEV sales")
    out(f"- BEV share of the EV car stock, 2025: {shr_stock.BEV[2025]:.1f}%")
    out(f"- FCEV (hydrogen) never exceeded {shr.FCEV.max():.2f}% of EV car sales")
    bev_minus = stock_pt.BEV - stock_pt.drop(columns="BEV").sum(axis=1)
    out(f"- BEV stock minus all other EV stock: {bev_minus[2015] / 1e6:.1f}M (2015) -> {bev_minus[2025] / 1e6:.1f}M (2025): "
        "the gap widens every year")
    out()
    fig, ax = plt.subplots(figsize=(8, 3.8))
    ax.stackplot(shr.index, shr.BEV, shr.PHEV, shr.FCEV, labels=["BEV", "PHEV", "FCEV"],
                 colors=[BLUE, ORANGE, GREY], alpha=0.9)
    ax.set_ylabel("% of EV car sales")
    ax.set_ylim(0, 100)
    ax.set_title("World EV car sales by powertrain", fontsize=10)
    ax.legend(loc="lower right", frameon=False)
    style(ax)
    fig.tight_layout()
    fig.savefig(FIG / "powertrain_share.png", dpi=160)
    plt.close(fig)

    # ------------------------------------------------------------------ 4. H1 infrastructure
    out("## 4. H1: do countries with more charging infrastructure adopt EVs faster?")
    out()
    c25 = ctry[ctry.Year == 2025].copy()
    c25["chargers_per_100k"] = c25.Charging_Total / c25[POP_COL] * 1e5
    c25["chargers_per_1000_evs"] = c25.Charging_Total / c25.EV_Stock_Cars_Total * 1e3
    rows = []

    def add(label, d, x, y="EV_Sales_Share_Cars", note=""):
        d = d.dropna(subset=[x, y])
        r, p = spearman(d[x], d[y])
        rows.append({"specification (2025 cross-section unless stated)": label, "n": len(d),
                     "Spearman rho": round(r, 2), "p": f"{p:.1e}" if p < 0.001 else f"{p:.3f}", "reading": note})

    add("total chargers vs EV sales share, countries with population data (presented)",
        c25.dropna(subset=[POP_COL]), "Charging_Total", note="moderate; total chargers mostly measures market size")
    add("total chargers vs EV sales share, all countries with charger data", c25, "Charging_Total",
        note="weaker with more countries")
    add("chargers per 100k people vs EV sales share", c25, "chargers_per_100k",
        note="strong, but both scale with how many EVs a country has")
    add("chargers per 1,000 EVs vs EV sales share", c25, "chargers_per_1000_evs",
        note="no relationship: high adopters do NOT have more chargers per EV")
    cd = ctry.sort_values(["Region_Country", "Year"]).copy()
    cd["chg_g"] = cd.groupby("Region_Country").Charging_Total.pct_change(fill_method=None) * 100
    cd["stk_g"] = cd.groupby("Region_Country").EV_Stock_Cars_Total.pct_change(fill_method=None) * 100
    add("YoY charger growth vs YoY EV stock growth (country-years, 2011-2025)", cd, "chg_g", "stk_g",
        note="weak (Pearson r = {:.2f})".format(cd.dropna(subset=["chg_g", "stk_g"])[["chg_g", "stk_g"]].corr().iloc[0, 1]))
    h1 = pd.DataFrame(rows)
    table(h1, "{:.2f}")
    lag = []
    for k in (0, 1, 2):
        d = cd.copy()
        d["chg_lag"] = d.groupby("Region_Country").chg_g.shift(k)
        d = d.dropna(subset=["chg_lag", "stk_g"])
        r, p = spearman(d.chg_lag, d.stk_g)
        lag.append(f"lag {k}y: rho {r:.2f} (n = {len(d)})")
    out("Charger growth in year t-k vs EV stock growth in year t: " + "; ".join(lag))
    out()
    out("Reading: countries with more chargers do have more EVs, but the relationship is about scale. "
        "Per EV, high-adoption countries do not have more chargers (Norway: 97% share with about 35 EVs per "
        "public charger). The data support an association, not a causal 'build chargers and EVs follow' claim.")
    out()
    fig, axes = plt.subplots(1, 3, figsize=(13, 4))
    specs = [("Charging_Total", "public chargers (log scale)", True),
             ("chargers_per_100k", "chargers per 100k people (log)", True),
             ("chargers_per_1000_evs", "chargers per 1,000 EVs (log)", True)]
    for ax, (x, lab, lg) in zip(axes, specs):
        d = c25.dropna(subset=[x, "EV_Sales_Share_Cars"])
        d = d[d[x] > 0]
        ax.scatter(d[x], d.EV_Sales_Share_Cars, s=22, color=BLUE, alpha=0.75)
        for _, r_ in d.nlargest(3, "EV_Sales_Share_Cars").iterrows():
            ax.annotate(r_.Region_Country, (r_[x], r_.EV_Sales_Share_Cars), fontsize=7, xytext=(3, 3),
                        textcoords="offset points")
        rho, p = spearman(d[x], d.EV_Sales_Share_Cars)
        ax.set_xscale("log" if lg else "linear")
        ax.set_xlabel(lab)
        ax.set_title(f"Spearman rho = {rho:.2f} (n = {len(d)})", fontsize=9)
        style(ax)
    axes[0].set_ylabel("EV share of new car sales, 2025 (%)")
    fig.suptitle("H1: the answer depends on how infrastructure is measured", fontsize=10)
    fig.tight_layout()
    fig.savefig(FIG / "h1_infrastructure_specifications.png", dpi=160)
    plt.close(fig)

    # ------------------------------------------------------------------ 5. H3 concentration
    out("## 5. H3: is growth concentrated in a handful of markets?")
    st = ctry.pivot_table(index="Region_Country", columns="Year", values="EV_Stock_Cars_Total", aggfunc="sum")
    pen = ctry.pivot_table(index="Region_Country", columns="Year", values="EV_Sales_Share_Cars", aggfunc="sum")
    growth = (st[2025] - st[2020]).dropna()
    total = growth.sum()
    srt = np.sort(growth.values)
    n = len(srt)
    gini = (2 * np.sum(np.arange(1, n + 1) * srt) - (n + 1) * srt.sum()) / (n * srt.sum())
    hhi = ((growth / total) ** 2).sum()
    top5 = growth.nlargest(5)
    out(f"- EV car stock growth 2020-2025 across {n} markets: {total / 1e6:.1f}M cars")
    out("- Top 5: " + ", ".join(f"{k} {v / total:.1%}" for k, v in top5.items())
        + f" = {top5.sum() / total:.1%} (top 10: {growth.nlargest(10).sum() / total:.1%})")
    out(f"- Gini {gini:.3f}, HHI {hhi:.3f} (above 0.25 = highly concentrated)")
    base_stock, base_pen = st[2020].reindex(growth.index), pen[2020].reindex(growth.index)
    v = base_pen.notna() & base_stock.notna() & (base_stock > 0)
    x, yv, z = base_pen[v].rank(), growth[v].rank(), base_stock[v].rank()
    rxy, rxz, ryz = np.corrcoef(x, yv)[0, 1], np.corrcoef(x, z)[0, 1], np.corrcoef(yv, z)[0, 1]
    partial = (rxy - rxz * ryz) / np.sqrt((1 - rxz ** 2) * (1 - ryz ** 2))
    nn = int(v.sum())
    t = partial * np.sqrt((nn - 3) / (1 - partial ** 2))
    p_part = 2 * (1 - stats.t.cdf(abs(t), nn - 3))
    out(f"- Market size (2020 stock) vs growth: Spearman {ryz:.2f}; 2020 penetration vs growth: {rxy:.2f}; "
        f"penetration vs growth controlling for size: partial rho {partial:.2f} (p = {p_part:.3f}, n = {nn})")
    out("- Reading: growth concentrates in LARGE markets; once size is accounted for, already-saturated markets "
        "(e.g. Norway) grow less.")
    out()
    top = growth.sort_values(ascending=False)
    fig, ax = plt.subplots(figsize=(8, 4))
    k = 12
    ax.bar(range(k), top.values[:k] / 1e6, color=[RED if i < 5 else BLUE for i in range(k)])
    ax.set_xticks(range(k), top.index[:k], rotation=45, ha="right", fontsize=8)
    ax.set_ylabel("EV car stock growth 2020-2025 (millions)")
    ax2 = ax.twinx()
    ax2.plot(range(k), (top.cumsum() / total * 100).values[:k], "k-o", ms=3)
    ax2.set_ylim(0, 105)
    ax2.set_ylabel("cumulative share of growth (%)")
    ax.set_title(f"H3: top 5 markets = {top5.sum() / total:.0%} of EV stock growth", fontsize=10)
    style(ax)
    fig.tight_layout()
    fig.savefig(FIG / "h3_growth_concentration.png", dpi=160)
    plt.close(fig)

    # ------------------------------------------------------------------ 6. 2035 outlook
    out("## 6. 2035 outlook (IEA scenarios)")
    out("CPS = Current Policies Scenario (only policies already in force); "
        "STEPS = Stated Policies Scenario (announced policies are implemented).")
    out()
    pst = proj[(proj.Parameter == "EV stock") & (proj.Mode == "Cars") & (proj.Powertrain == "EV")] \
        .pivot_table(index="Region_Country", columns="Category", values="Value")
    pst = pst / 1e6
    pst.columns = ["EV cars 2035 CPS (M)", "EV cars 2035 STEPS (M)"]
    pst["STEPS / CPS"] = pst.iloc[:, 1] / pst.iloc[:, 0]
    pcp = proj[proj.Parameter == "EV charging points"].groupby(["Region_Country", "Category"]).Value.sum().unstack()
    pst["public chargers CPS (M)"] = pcp["Projection-CPS"] / 1e6
    pst["public chargers STEPS (M)"] = pcp["Projection-STEPS"] / 1e6
    table(pst.reset_index().rename(columns={"Region_Country": "region"}), "{:,.2f}")
    out(f"World public chargers today: {y1.Charging_Total / 1e6:.2f}M; needed by 2035: "
        f"{pcp.loc['World', 'Projection-CPS'] / 1e6:.1f}M (CPS) to {pcp.loc['World', 'Projection-STEPS'] / 1e6:.1f}M (STEPS)")
    out()
    (RES / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwritten: {RES.relative_to(ROOT)}/RESULTS.md and {len(list(FIG.glob('*.png')))} figures")


if __name__ == "__main__":
    main()
